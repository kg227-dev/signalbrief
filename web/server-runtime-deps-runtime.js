    sendEmail,
    sendTelegramText,
    formatTimeEt,
    parseEtNowParts,
    computeNextDeliveryEt,
    formatDaysLabel,
    computeQualityTrend,
    estimateSandboxCost,
    runSandboxPipeline,
    requestSchedulerWorkerRestart,

    // Public route deps
    assetVersion,
    findUserByToken: findUserByTokenForPublic,
    loadEngagementEvents: loadEngagementEventsForPublic,
    renderPublicDigestMissingPage,
    formatPublicDigestDateLabel,
